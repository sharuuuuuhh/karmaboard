/**
 * Returns true if the group is one of the 7 fixed official campus teams:
 * LEADS, TECH, CREATIVE, MEDIA, CONTENT, OPERATION, MARKETING.
 * All other groups return false and belong to the "Groups" section.
 */
export function isOfficialTeam(groupOrName) {
  if (!groupOrName) return false;
  const raw =
    typeof groupOrName === "string"
      ? groupOrName
      : groupOrName.name || groupOrName.id || "";
  const clean = String(raw).toLowerCase().replace(/^grp-/, "").trim();
  return OFFICIAL_TEAMS_SET.has(clean);
}

